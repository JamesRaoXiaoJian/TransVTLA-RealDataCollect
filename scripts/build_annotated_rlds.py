#!/usr/bin/env python3
"""Build RLDS/TFDS episodes from TransVTLA annotation manifests.

This converter consumes the annotation_manifest*.csv generated by
scripts/auto_annotate_dataset.py. Labels, prompts, success flags, and the
two-stage action-head labels come from the manifest rather than from directory
names.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import os
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterable

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from session_schema import (  # noqa: E402
    DEPTH_EXT,
    RGB_EXT,
    CameraDirs,
    SessionLayout,
    depth_path,
    gripper_state_csv_path,
    read_frame_records,
    rgb_path,
    robot_state_csv_path,
    sync_index_path,
)

VISUAL_FPS = 30
TACTILE_SHAPE = (16, 20)
DEPTH_IMAGE_SHAPE = (224, 224, 1)
PRESSURE_CHANNELS = [
    "CH51", "CH50",
    "CH63", "CH60", "CH57", "CH64", "CH61", "CH58", "CH49", "CH62", "CH59",
    "CH47", "CH44", "CH41", "CH48", "CH45", "CH42", "CH33", "CH46", "CH43",
]
MAX_PRESSURE_DROP = 3200.0

VISUAL_STEMS_CACHE: dict[Path, tuple[list[str], Any | None, str]] = {}
ROBOT_CACHE: dict[Path, tuple[Any, Any]] = {}
GRIPPER_CACHE: dict[Path, tuple[Any, Any]] = {}
SYNC_CACHE: dict[Path, list[dict[str, str]]] = {}
TACTILE_CACHE: dict[Path, TactileData | None] = {}


@dataclass(frozen=True)
class EpisodeRow:
    index: int
    row: dict[str, str]
    session_dir: Path

    @property
    def annotation_key(self) -> str:
        return value_or(self.row.get("annotation_key"), f"row_{self.index:06d}")

    @property
    def rel_path(self) -> str:
        return value_or(self.row.get("rel_path"), str(self.session_dir))

    @property
    def data_source(self) -> str:
        return value_or(self.row.get("data_source"), "unknown")

    @property
    def needs_review(self) -> bool:
        return parse_bool(self.row.get("needs_review"))


@dataclass
class EpisodeBuildResult:
    steps: list[dict[str, Any]] | None
    frames: int
    reason: str = ""


@dataclass
class TactileData:
    data: Any
    timestamps: Any | None
    time_base: str = ""


def value_or(value: Any, default: str = "") -> str:
    if value is None:
        return default
    text = str(value).strip()
    return text if text else default


def parse_bool(value: Any) -> bool:
    return str(value).strip().lower() in {"1", "true", "yes", "y"}


def parse_int(value: Any, default: int | None = None) -> int | None:
    if value in (None, ""):
        return default
    try:
        return int(float(str(value)))
    except ValueError:
        return default


def parse_float(value: Any, default: float = 0.0) -> float:
    if value in (None, ""):
        return default
    try:
        return float(str(value))
    except ValueError:
        return default


def repo_path(path: Path | str) -> Path:
    path = Path(path)
    return path if path.is_absolute() else REPO_ROOT / path


def read_csv_rows(path: Path) -> list[dict[str, str]]:
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def safe_is_dir(path: Path) -> bool:
    try:
        return path.is_dir()
    except OSError:
        return False


def safe_stems(directory: Path | None, suffix: str) -> set[str]:
    if directory is None:
        return set()
    try:
        if not directory.is_dir():
            return set()
        return {p.stem for p in directory.glob(f"*{suffix}") if p.is_file()}
    except OSError:
        return set()


def resolve_session_layout_safe(session_dir: Path) -> SessionLayout | None:
    world_rgb = session_dir / "world_camera" / "rgb"
    world_depth = session_dir / "world_camera" / "depth"
    wrist_rgb = session_dir / "wrist_camera" / "rgb"
    wrist_depth = session_dir / "wrist_camera" / "depth"
    if safe_is_dir(world_rgb) and safe_is_dir(wrist_rgb):
        return SessionLayout(
            root=session_dir,
            world=CameraDirs(
                name="world_camera",
                rgb=world_rgb,
                depth=world_depth if safe_is_dir(world_depth) else None,
            ),
            wrist=CameraDirs(
                name="wrist_camera",
                rgb=wrist_rgb,
                depth=wrist_depth if safe_is_dir(wrist_depth) else None,
            ),
            is_legacy=False,
        )

    legacy_world_rgb = session_dir / "dji"
    legacy_wrist_rgb = session_dir / "realsense_rgb"
    legacy_wrist_depth = session_dir / "realsense_depth"
    if safe_is_dir(legacy_world_rgb) and safe_is_dir(legacy_wrist_rgb):
        return SessionLayout(
            root=session_dir,
            world=CameraDirs(name="world_camera", rgb=legacy_world_rgb, depth=None),
            wrist=CameraDirs(
                name="wrist_camera",
                rgb=legacy_wrist_rgb,
                depth=legacy_wrist_depth if safe_is_dir(legacy_wrist_depth) else None,
            ),
            is_legacy=True,
        )
    return None


def visual_stems(session_dir: Path) -> tuple[list[str], Any | None, str]:
    cached = VISUAL_STEMS_CACHE.get(session_dir)
    if cached is not None:
        return cached

    layout = resolve_session_layout_safe(session_dir)
    if layout is None:
        result = ([], None, "missing dual RealSense or legacy RGB layout")
        VISUAL_STEMS_CACHE[session_dir] = result
        return result

    records = read_frame_records(session_dir)
    if records:
        stems: list[str] = []
        for idx, record in enumerate(records):
            stem = value_or(record.get("frame_stem"))
            if not stem:
                frame_id = parse_int(record.get("frame_id"), idx + 1) or idx + 1
                stem = f"{frame_id:04d}"
            if rgb_path(layout.world, stem).is_file() and rgb_path(layout.wrist, stem).is_file():
                stems.append(stem)
        if stems:
            result = (stems, layout, "")
            VISUAL_STEMS_CACHE[session_dir] = result
            return result

    world = safe_stems(layout.world.rgb, RGB_EXT)
    wrist = safe_stems(layout.wrist.rgb, RGB_EXT)
    stems = sorted(world & wrist)
    if not stems:
        result = ([], layout, "missing common RGB frames")
        VISUAL_STEMS_CACHE[session_dir] = result
        return result
    result = (stems, layout, "")
    VISUAL_STEMS_CACHE[session_dir] = result
    return result


def _fieldnames(row: dict[str, str]) -> set[str]:
    return {key for key in row.keys() if key is not None}


def load_robot_csv(path: Path, np: Any) -> tuple[Any, Any]:
    cached = ROBOT_CACHE.get(path)
    if cached is not None:
        return cached
    if not path.is_file():
        result = (np.array([], dtype=np.int64), np.zeros((0, 6), dtype=np.float32))
        ROBOT_CACHE[path] = result
        return result

    timestamps: list[int] = []
    poses: list[list[float]] = []
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        headers = set(reader.fieldnames or [])
        pose_cols = [f"pose_{i}" for i in range(1, 7)]
        use_named_pose = all(col in headers for col in pose_cols)
        for row in reader:
            ts = parse_int(row.get("timestamp_us"))
            if ts is None:
                continue
            try:
                if use_named_pose:
                    pose = [float(row[col]) for col in pose_cols]
                else:
                    values = list(row.values())
                    pose = [float(v) for v in values[8:14]]
            except (TypeError, ValueError):
                continue
            if len(pose) != 6:
                continue
            timestamps.append(ts)
            poses.append(pose)
    result = (np.asarray(timestamps, dtype=np.int64), np.asarray(poses, dtype=np.float32))
    ROBOT_CACHE[path] = result
    return result


def load_gripper_csv(path: Path, np: Any) -> tuple[Any, Any]:
    cached = GRIPPER_CACHE.get(path)
    if cached is not None:
        return cached
    if not path.is_file():
        result = (np.array([], dtype=np.int64), np.array([], dtype=np.float32))
        GRIPPER_CACHE[path] = result
        return result

    timestamps: list[int] = []
    positions: list[float] = []
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        headers = _fieldnames({"": "", **{name: "" for name in reader.fieldnames or []}})
        position_col = "gripper_pos" if "gripper_pos" in headers else ""
        for row in reader:
            ts = parse_int(row.get("timestamp_us"))
            if ts is None:
                continue
            if position_col:
                raw_pos = row.get(position_col)
            else:
                values = list(row.values())
                raw_pos = values[5] if len(values) > 5 else None
            try:
                pos = float(raw_pos)
            except (TypeError, ValueError):
                continue
            timestamps.append(ts)
            positions.append(pos)
    result = (np.asarray(timestamps, dtype=np.int64), np.asarray(positions, dtype=np.float32))
    GRIPPER_CACHE[path] = result
    return result


def load_sync_index(path: Path) -> list[dict[str, str]]:
    cached = SYNC_CACHE.get(path)
    if cached is not None:
        return cached
    if not path.is_file():
        SYNC_CACHE[path] = []
        return []
    with open(path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    SYNC_CACHE[path] = rows
    return rows


def npz_text(data: Any, key: str) -> str:
    if key not in data:
        return ""
    value = data[key]
    try:
        if hasattr(value, "shape") and value.shape == ():
            value = value.item()
    except Exception:
        pass
    if isinstance(value, bytes):
        return value.decode("utf-8", "replace")
    return str(value)


def load_tactile_npz(session_dir: Path, np: Any) -> TactileData | None:
    cached = TACTILE_CACHE.get(session_dir)
    if session_dir in TACTILE_CACHE:
        return cached
    npz_dir = session_dir / "preprocessed_pressure"
    candidates = [npz_dir / f"{session_dir.name}.npz"]
    if npz_dir.is_dir():
        try:
            candidates.extend(sorted(p for p in npz_dir.glob("*.npz") if p not in candidates))
        except OSError:
            pass

    for path in candidates:
        if not path.is_file():
            continue
        try:
            data = np.load(str(path))
            tactile = data["data"].astype(np.float32)
            if "window_center_host_us" in data:
                ts = data["window_center_host_us"].astype(np.int64)
                time_base = "host_monotonic"
            elif "window_center_time_us" in data:
                ts = data["window_center_time_us"].astype(np.int64)
                time_base = npz_text(data, "time_base")
            elif "window_center_sensor_us" in data:
                ts = data["window_center_sensor_us"].astype(np.int64)
                time_base = "sensor_timestamp"
            else:
                ts = None
                time_base = ""
            result = TactileData(tactile, ts, time_base)
            TACTILE_CACHE[session_dir] = result
            return result
        except Exception:
            continue
    TACTILE_CACHE[session_dir] = None
    return None


def load_raw_pressure_csv(session_dir: Path, np: Any) -> tuple[Any, Any] | None:
    path = session_dir / "pressure" / "pressure.csv"
    if not path.is_file():
        return None
    timestamps: list[int] = []
    rows: list[list[float]] = []
    try:
        with path.open(newline="", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            headers = set(reader.fieldnames or [])
            if not set(PRESSURE_CHANNELS).issubset(headers):
                return None
            for row in reader:
                ts = parse_int(row.get("host_monotonic_us"))
                if ts is None:
                    ts = parse_int(row.get("sensor_timestamp_us"))
                if ts is None:
                    continue
                try:
                    values = [float(row[channel]) for channel in PRESSURE_CHANNELS]
                except (TypeError, ValueError):
                    continue
                timestamps.append(ts)
                rows.append(values)
    except OSError:
        return None
    if not rows:
        return None
    pressure = np.asarray(rows, dtype=np.float32)
    # Keep CH58 aligned with the real clean-data convention.
    ch58 = PRESSURE_CHANNELS.index("CH58")
    pressure[:, ch58] = (
        pressure[:, PRESSURE_CHANNELS.index("CH61")]
        + pressure[:, PRESSURE_CHANNELS.index("CH57")]
        + pressure[:, PRESSURE_CHANNELS.index("CH59")]
    ) / 3.0
    return np.asarray(timestamps, dtype=np.int64), pressure


def raw_pressure_tactile(session_dir: Path, timestamps: Any, np: Any) -> Any | None:
    loaded = load_raw_pressure_csv(session_dir, np)
    if loaded is None or len(timestamps) == 0:
        return None
    pressure_ts, pressure = loaded
    if len(pressure_ts) == 0 or len(pressure) == 0:
        return None
    baseline_count = min(50, len(pressure))
    baseline = np.median(pressure[:baseline_count], axis=0)
    delta = np.maximum(baseline[None, :] - pressure, 0.0)
    normalized = np.clip(delta / MAX_PRESSURE_DROP, 0.0, 1.0).astype(np.float32)

    centers = nearest_indices(timestamps, pressure_ts, np)
    windows = np.zeros((len(timestamps), *TACTILE_SHAPE), dtype=np.float32)
    for out_i, center in enumerate(centers):
        start = int(center) - TACTILE_SHAPE[0] + 1
        indices = np.arange(start, start + TACTILE_SHAPE[0])
        indices = np.clip(indices, 0, len(normalized) - 1)
        windows[out_i] = normalized[indices]
    return windows


def nearest_indices(target_ts: Any, source_ts: Any, np: Any) -> Any:
    if len(target_ts) == 0 or len(source_ts) == 0:
        return np.array([], dtype=np.int64)
    if len(source_ts) == 1:
        return np.zeros(len(target_ts), dtype=np.int64)
    idx = np.searchsorted(source_ts, target_ts, side="left")
    idx = np.clip(idx, 1, len(source_ts) - 1)
    left = source_ts[idx - 1]
    right = source_ts[idx]
    pick_left = (target_ts - left) <= (right - target_ts)
    return np.where(pick_left, idx - 1, idx)


def wrap_to_pi(values: Any, np: Any) -> Any:
    return (values + np.pi) % (2 * np.pi) - np.pi


def normalize_gripper_if_needed(gripper: Any, np: Any, enabled: bool) -> Any:
    gripper = gripper.astype(np.float32)
    if not enabled or len(gripper) == 0:
        return gripper
    max_value = float(np.nanmax(gripper)) if len(gripper) else 0.0
    if max_value > 1.5:
        gripper = gripper / 1000.0
    return np.clip(gripper, 0.0, 1.0).astype(np.float32)


def resample_indices(source_count: int, target_count: int, np: Any) -> Any:
    if source_count <= 0 or target_count <= 0:
        return np.array([], dtype=np.int64)
    return np.linspace(0, source_count - 1, target_count).astype(np.int64)


def downsample_stems(
    session_dir: Path,
    stems: list[str],
    target_fps: float,
    robot_ts: Any,
    np: Any,
) -> list[str]:
    if target_fps <= 0 or abs(target_fps - VISUAL_FPS) < 1e-6 or len(stems) < 2:
        return stems
    frame_ts = frame_timestamps_from_records(session_dir, stems, robot_ts, np)
    if len(frame_ts) != len(stems) or len(frame_ts) < 2:
        return stems
    interval_us = int(round(1_000_000.0 / target_fps))
    targets = np.arange(int(frame_ts[0]), int(frame_ts[-1]) + 1, interval_us, dtype=np.int64)
    indices = nearest_indices(targets, frame_ts, np)
    selected: list[str] = []
    seen: set[int] = set()
    for index in indices:
        idx = int(index)
        if idx in seen:
            continue
        seen.add(idx)
        selected.append(stems[idx])
    return selected if len(selected) >= 2 else stems


def frame_timestamps_from_records(session_dir: Path, stems: list[str], robot_ts: Any, np: Any) -> Any:
    records = read_frame_records(session_dir)
    if records:
        by_stem: dict[str, int] = {}
        for idx, record in enumerate(records):
            ts = parse_int(record.get("capture_monotonic_us"))
            if ts is None:
                continue
            stem = value_or(record.get("frame_stem"))
            if not stem:
                frame_id = parse_int(record.get("frame_id"), idx + 1) or idx + 1
                stem = f"{frame_id:04d}"
            by_stem[stem] = ts
        timestamps = [by_stem.get(stem) for stem in stems]
        if all(ts is not None for ts in timestamps):
            return np.asarray(timestamps, dtype=np.int64)

    if len(robot_ts) > 0:
        anchor = int(robot_ts[0])
    else:
        anchor = 0
    interval_us = int(1_000_000 / VISUAL_FPS)
    return np.asarray([anchor + i * interval_us for i in range(len(stems))], dtype=np.int64)


def aligned_state(
    session_dir: Path,
    stems: list[str],
    robot_ts: Any,
    robot_poses: Any,
    gripper_ts: Any,
    gripper_pos: Any,
    np: Any,
) -> tuple[Any, Any, Any]:
    sync_rows = load_sync_index(sync_index_path(session_dir))
    if sync_rows:
        stem_set = set(stems)
        sync_rows = [row for row in sync_rows if row.get("frame_stem") in stem_set]
        sync_by_stem = {str(row.get("frame_stem")): row for row in sync_rows}
        ordered = [sync_by_stem.get(stem) for stem in stems]
        if all(row is not None for row in ordered):
            timestamps = np.asarray(
                [parse_int(row.get("capture_monotonic_us"), 0) or 0 for row in ordered],
                dtype=np.int64,
            )
            poses = np.zeros((len(stems), 6), dtype=np.float32)
            gripper = np.zeros(len(stems), dtype=np.float32)
            for i, row in enumerate(ordered):
                robot_idx = parse_int(row.get("robot_index"), -1)
                if robot_idx is not None and 0 <= robot_idx < len(robot_poses):
                    poses[i] = robot_poses[robot_idx]
                gripper_idx = parse_int(row.get("gripper_index"), -1)
                if gripper_idx is not None and 0 <= gripper_idx < len(gripper_pos):
                    gripper[i] = gripper_pos[gripper_idx]
            return timestamps, poses, gripper

    timestamps = frame_timestamps_from_records(session_dir, stems, robot_ts, np)
    if len(robot_poses) == 0:
        return timestamps, np.zeros((len(stems), 6), dtype=np.float32), np.zeros(len(stems), dtype=np.float32)

    robot_indices = nearest_indices(timestamps, robot_ts, np)
    poses = robot_poses[robot_indices] if len(robot_indices) else np.zeros((len(stems), 6), dtype=np.float32)
    gripper = np.zeros(len(stems), dtype=np.float32)
    if len(gripper_ts) and len(gripper_pos):
        gripper_indices = nearest_indices(timestamps, gripper_ts, np)
        if len(gripper_indices):
            gripper = gripper_pos[gripper_indices]
    return timestamps, poses, gripper


def aligned_tactile(session_dir: Path, timestamps: Any, np: Any) -> Any | None:
    tactile_data = load_tactile_npz(session_dir, np)
    if tactile_data is None or len(tactile_data.data) == 0:
        return None
    tactile = tactile_data.data
    tactile_ts = tactile_data.timestamps
    if tactile_ts is not None and len(tactile_ts) > 0 and tactile_data.time_base == "host_monotonic":
        indices = nearest_indices(timestamps, tactile_ts, np)
        if len(indices) != len(timestamps):
            indices = resample_indices(len(tactile), len(timestamps), np)
        elif len(indices):
            dt = np.abs(tactile_ts[indices] - timestamps)
            if float(np.median(dt)) > 1_000_000.0:
                indices = resample_indices(len(tactile), len(timestamps), np)
    else:
        indices = resample_indices(len(tactile), len(timestamps), np)
    return tactile[indices] if len(indices) else None


def stage_arrays(row: dict[str, str], frame_count: int, np: Any) -> tuple[Any, Any, list[str]]:
    labels = np.zeros(frame_count, dtype=np.int64)
    use_tactile = np.zeros(frame_count, dtype=np.bool_)
    names = ["visual_pre_contact" for _ in range(frame_count)]

    segments_text = value_or(row.get("stage_segments_json"))
    if segments_text:
        try:
            segments = json.loads(segments_text)
        except json.JSONDecodeError:
            segments = []
        for segment in segments:
            start = max(0, parse_int(segment.get("start_frame_index"), 0) or 0)
            end = parse_int(segment.get("end_frame_index"), frame_count - 1)
            end = frame_count - 1 if end is None else min(frame_count - 1, end)
            if start > end or start >= frame_count:
                continue
            stage = parse_int(segment.get("stage"), 0) or 0
            tactile_on = parse_bool(segment.get("use_tactile"))
            name = value_or(segment.get("name"), "unknown")
            labels[start : end + 1] = stage
            use_tactile[start : end + 1] = tactile_on
            for i in range(start, end + 1):
                names[i] = name
        return labels, use_tactile, names

    stage1 = parse_int(row.get("stage1_start_frame_index"))
    if stage1 is None:
        return labels, use_tactile, names
    stage1 = min(max(stage1, 0), frame_count)
    labels[stage1:] = 1
    use_tactile[stage1:] = True
    for i in range(stage1, frame_count):
        names[i] = "tactile_guided_contact"
    return labels, use_tactile, names


def row_has_stage_annotation(row: dict[str, str]) -> bool:
    return bool(value_or(row.get("stage_segments_json"))) or parse_int(row.get("stage1_start_frame_index")) is not None


def infer_stage_from_tactile(tactile: Any | None, np: Any) -> tuple[int | None, Any | None]:
    if tactile is None or len(tactile) == 0:
        return None, None
    try:
        strength = tactile.reshape((len(tactile), -1)).max(axis=1)
    except Exception:
        return None, None
    active = np.where(strength > 0.03)[0]
    if len(active) == 0:
        return None, strength
    return int(active[0]), strength


def force_range(row: dict[str, str]) -> str:
    return f"{parse_float(row.get('force_min')):.3f}-{parse_float(row.get('force_max')):.3f}"


def contextual_prompt(row: dict[str, str], phase: str) -> str:
    instruction = value_or(row.get("language_instruction"), "Pick up the target object.")
    obj = value_or(row.get("object_type"), "unknown")
    material = value_or(row.get("material"), "unknown")
    return (
        f"What action should the robot take to execute: {instruction}\n"
        f"CTX:OBJ={obj}|MAT={material}|PHASE={phase}|FORCE={force_range(row)}"
    )


def _zeros(shape: tuple[int, ...], dtype: str, np: Any) -> Any:
    return np.zeros(shape, dtype=getattr(np, dtype))


def load_image(path: Path, cv2: Any, np: Any, image_size: int) -> Any | None:
    try:
        img = cv2.imread(str(path), cv2.IMREAD_COLOR)
    except Exception:
        return None
    if img is None:
        return None
    img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
    return cv2.resize(img, (image_size, image_size), interpolation=cv2.INTER_AREA).astype(np.uint8)


def load_depth(path: Path | None, cv2: Any, np: Any, image_size: int, invalid_to_zero: bool = False) -> Any:
    if path is None:
        return _zeros((image_size, image_size, 1), "uint16", np)
    try:
        if not path.is_file():
            return _zeros((image_size, image_size, 1), "uint16", np)
        depth = cv2.imread(str(path), cv2.IMREAD_UNCHANGED)
    except Exception:
        return _zeros((image_size, image_size, 1), "uint16", np)
    if depth is None:
        return _zeros((image_size, image_size, 1), "uint16", np)
    if depth.ndim == 3:
        depth = depth[:, :, 0]
    if depth.dtype != np.uint16:
        depth = depth.astype(np.uint16)
    if invalid_to_zero:
        depth = depth.copy()
        depth[depth == np.iinfo(np.uint16).max] = 0
    depth = cv2.resize(depth, (image_size, image_size), interpolation=cv2.INTER_NEAREST)
    return depth[:, :, None]


def process_episode(
    episode: EpisodeRow,
    np: Any,
    cv2: Any | None = None,
    image_size: int = 224,
    load_arrays: bool = True,
    mask_tactile_before_stage1: bool = True,
    normalize_gripper: bool = False,
    absolute_gripper_action: bool = False,
    wrap_euler_action: bool = False,
    raw_pressure_tactile_enabled: bool = False,
    target_fps: float = 0.0,
    depth_invalid_to_zero: bool = False,
) -> EpisodeBuildResult:
    stems, layout, reason = visual_stems(episode.session_dir)
    if not stems or layout is None:
        return EpisodeBuildResult(None, 0, reason)

    robot_ts, robot_poses = load_robot_csv(robot_state_csv_path(episode.session_dir), np)
    if len(robot_ts) == 0 or len(robot_poses) == 0:
        return EpisodeBuildResult(None, len(stems), "missing robot_state")
    stems = downsample_stems(episode.session_dir, stems, target_fps, robot_ts, np)
    gripper_ts, gripper_pos = load_gripper_csv(gripper_state_csv_path(episode.session_dir), np)

    timestamps, poses, gripper = aligned_state(
        episode.session_dir, stems, robot_ts, robot_poses, gripper_ts, gripper_pos, np
    )
    n = min(len(stems), len(poses), len(gripper), len(timestamps))
    stems = stems[:n]
    timestamps = timestamps[:n]
    poses = poses[:n]
    gripper = normalize_gripper_if_needed(gripper[:n], np, normalize_gripper)
    if n < 2:
        return EpisodeBuildResult(None, n, "too few aligned frames")

    tactile = aligned_tactile(episode.session_dir, timestamps, np)
    if tactile is None and raw_pressure_tactile_enabled:
        tactile = raw_pressure_tactile(episode.session_dir, timestamps, np)
    stage_label, use_tactile, phase_names = stage_arrays(episode.row, n, np)
    if not row_has_stage_annotation(episode.row):
        inferred_stage1, _ = infer_stage_from_tactile(tactile, np)
        if inferred_stage1 is not None and 0 <= inferred_stage1 < n:
            stage_label[inferred_stage1:] = 1
            use_tactile[inferred_stage1:] = True
            for phase_i in range(inferred_stage1, n):
                phase_names[phase_i] = "tactile_guided_contact"

    if not load_arrays:
        return EpisodeBuildResult([], n, "")
    if cv2 is None:
        raise RuntimeError("cv2 is required when load_arrays=True")

    zero_tactile = np.zeros(TACTILE_SHAPE, dtype=np.float32)
    steps: list[dict[str, Any]] = []
    success = parse_bool(episode.row.get("success"))
    base_instruction = value_or(episode.row.get("language_instruction"), "Pick up the target object.")
    object_type = value_or(episode.row.get("object_type"), "unknown")
    material = value_or(episode.row.get("material"), "unknown")
    item_type = value_or(episode.row.get("item_type"), value_or(episode.row.get("object_label"), object_type))

    for i, stem in enumerate(stems):
        primary = load_image(rgb_path(layout.world, stem), cv2, np, image_size)
        wrist = load_image(rgb_path(layout.wrist, stem), cv2, np, image_size)
        if primary is None or wrist is None:
            return EpisodeBuildResult(None, n, f"failed to load RGB frame {stem}")

        if i < n - 1:
            delta = poses[i + 1] - poses[i]
            if wrap_euler_action:
                delta[3:6] = wrap_to_pi(delta[3:6], np)
            gripper_target = gripper[i + 1] if absolute_gripper_action else gripper[i + 1] - gripper[i]
            action = np.concatenate([delta, [gripper_target]]).astype(np.float32)
        else:
            action = np.zeros(7, dtype=np.float32)
            if absolute_gripper_action:
                action[6] = gripper[i]

        tactile_frame = zero_tactile
        if tactile is not None and i < len(tactile):
            tactile_frame = tactile[i].astype(np.float32)
        if mask_tactile_before_stage1 and not bool(use_tactile[i]):
            tactile_frame = zero_tactile

        phase = phase_names[i]
        is_last = i == n - 1
        steps.append({
            "observation": {
                "primary_image": primary,
                "wrist_image": wrist,
                "primary_depth": load_depth(
                    depth_path(layout.world, stem), cv2, np, image_size, invalid_to_zero=depth_invalid_to_zero
                ),
                "wrist_depth": load_depth(
                    depth_path(layout.wrist, stem), cv2, np, image_size, invalid_to_zero=depth_invalid_to_zero
                ),
                "state": np.concatenate([poses[i], [gripper[i]]]).astype(np.float32),
                "tactile": tactile_frame,
            },
            "action": action,
            "reward": np.float32(1.0 if is_last and success else 0.0),
            "is_first": i == 0,
            "is_last": is_last,
            "is_terminal": is_last,
            "language_instruction": base_instruction,
            "action_prompt": contextual_prompt(episode.row, phase),
            "object_type": object_type,
            "object_label": value_or(episode.row.get("object_label"), object_type),
            "item_type": item_type,
            "material": material,
            "phase": phase,
            "stage_label": np.int64(stage_label[i]),
            "use_tactile": bool(use_tactile[i]),
            "fragility": np.float32(parse_float(episode.row.get("fragility"))),
            "slip_risk": np.float32(parse_float(episode.row.get("slip_risk"))),
            "depth_uncertainty": np.float32(parse_float(episode.row.get("depth_uncertainty"))),
            "force_min": np.float32(parse_float(episode.row.get("force_min"))),
            "force_max": np.float32(parse_float(episode.row.get("force_max"))),
        })

    return EpisodeBuildResult(steps, n, "")


def load_numpy() -> Any:
    try:
        import numpy as np  # type: ignore
    except ImportError as exc:
        raise SystemExit("numpy is required for RLDS conversion") from exc
    return np


def load_cv2() -> Any:
    try:
        import cv2  # type: ignore
    except ImportError as exc:
        raise SystemExit("opencv-python is required for image/depth conversion") from exc
    return cv2


def load_tfds() -> Any:
    os.environ.setdefault("CUDA_VISIBLE_DEVICES", "-1")
    os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")
    try:
        import tensorflow_datasets as tfds  # type: ignore
    except ImportError as exc:
        raise SystemExit("tensorflow-datasets is required for --build") from exc
    return tfds


def select_rows(args: argparse.Namespace) -> list[EpisodeRow]:
    rows = read_csv_rows(repo_path(args.manifest))
    selected: list[EpisodeRow] = []
    for idx, row in enumerate(rows):
        data_source = value_or(row.get("data_source"), "unknown")
        if args.data_source != "all" and data_source != args.data_source:
            continue
        if args.split and value_or(row.get("split")) != args.split:
            continue
        if not args.include_unusable and not parse_bool(row.get("usable_for_aligned_training")):
            continue
        if not args.allow_review and parse_bool(row.get("needs_review")):
            continue
        rel_path = value_or(row.get("rel_path"))
        if not rel_path:
            continue
        selected.append(EpisodeRow(index=idx, row=row, session_dir=repo_path(rel_path)))
        if args.max_episodes is not None and len(selected) >= args.max_episodes:
            break
    return selected


def make_episode_key(prefix: str, episode: EpisodeRow, ordinal: int) -> str:
    text = f"{ordinal}:{episode.annotation_key}:{episode.rel_path}"
    digest = hashlib.md5(text.encode("utf-8")).hexdigest()[:10]
    return f"{prefix}_{ordinal:06d}_{digest}"


def dry_run(args: argparse.Namespace) -> int:
    np = load_numpy()
    episodes = select_rows(args)
    failures: list[tuple[str, str]] = []
    frame_counts: list[int] = []
    stage0 = 0
    stage1 = 0

    for episode in episodes:
        result = process_episode(
            episode,
            np=np,
            load_arrays=False,
            image_size=args.image_size,
            mask_tactile_before_stage1=not args.no_mask_tactile_before_stage1,
            normalize_gripper=args.normalize_gripper_01,
            absolute_gripper_action=args.absolute_gripper_action,
            wrap_euler_action=args.wrap_euler_action,
            raw_pressure_tactile_enabled=args.raw_pressure_tactile,
            target_fps=args.target_fps,
            depth_invalid_to_zero=args.depth_invalid_to_zero,
        )
        if result.reason:
            failures.append((episode.rel_path, result.reason))
            continue
        frame_counts.append(result.frames)
        labels, _, _ = stage_arrays(episode.row, result.frames, np)
        stage0 += int((labels == 0).sum())
        stage1 += int((labels == 1).sum())

    ok = len(frame_counts)
    print(f"manifest={repo_path(args.manifest)}")
    print(f"selected={len(episodes)} ok={ok} failed={len(failures)}")
    if frame_counts:
        print(
            "frames "
            f"min={min(frame_counts)} max={max(frame_counts)} "
            f"mean={sum(frame_counts) / len(frame_counts):.2f}"
        )
    print(f"stage_frames stage0={stage0} stage1={stage1}")
    for rel_path, reason in failures[: args.show_failures]:
        print(f"[failed] {rel_path}: {reason}")
    if len(failures) > args.show_failures:
        print(f"... {len(failures) - args.show_failures} more failures")
    return 1 if failures and args.fail_on_error else 0


def build(args: argparse.Namespace) -> int:
    np = load_numpy()
    cv2 = load_cv2()
    tfds = load_tfds()
    episodes = select_rows(args)
    if not episodes:
        raise SystemExit("No episodes selected from manifest")

    image_size = args.image_size
    mask_tactile_before_stage1 = not args.no_mask_tactile_before_stage1

    class TransvtlaAnnotatedRlds(tfds.core.GeneratorBasedBuilder):
        VERSION = tfds.core.Version(args.version)

        def __init__(self, *, data_dir: str | Path, episode_rows: list[EpisodeRow], **kwargs: Any):
            self.episode_rows = episode_rows
            super().__init__(data_dir=data_dir, **kwargs)

        def _info(self) -> Any:
            return tfds.core.DatasetInfo(
                builder=self,
                description="TransVTLA annotated real/sim RLDS dataset.",
                features=tfds.features.FeaturesDict({
                    "steps": tfds.features.Dataset({
                        "observation": tfds.features.FeaturesDict({
                            "primary_image": tfds.features.Image(
                                shape=(image_size, image_size, 3), dtype=np.uint8
                            ),
                            "wrist_image": tfds.features.Image(
                                shape=(image_size, image_size, 3), dtype=np.uint8
                            ),
                            "primary_depth": tfds.features.Tensor(
                                shape=(image_size, image_size, 1), dtype=np.uint16
                            ),
                            "wrist_depth": tfds.features.Tensor(
                                shape=(image_size, image_size, 1), dtype=np.uint16
                            ),
                            "state": tfds.features.Tensor(shape=(7,), dtype=np.float32),
                            "tactile": tfds.features.Tensor(shape=TACTILE_SHAPE, dtype=np.float32),
                        }),
                        "action": tfds.features.Tensor(shape=(7,), dtype=np.float32),
                        "reward": tfds.features.Scalar(dtype=np.float32),
                        "is_first": tfds.features.Scalar(dtype=np.bool_),
                        "is_last": tfds.features.Scalar(dtype=np.bool_),
                        "is_terminal": tfds.features.Scalar(dtype=np.bool_),
                        "language_instruction": tfds.features.Text(),
                        "action_prompt": tfds.features.Text(),
                        "object_type": tfds.features.Text(),
                        "object_label": tfds.features.Text(),
                        "item_type": tfds.features.Text(),
                        "material": tfds.features.Text(),
                        "phase": tfds.features.Text(),
                        "stage_label": tfds.features.Scalar(dtype=np.int64),
                        "use_tactile": tfds.features.Scalar(dtype=np.bool_),
                        "fragility": tfds.features.Scalar(dtype=np.float32),
                        "slip_risk": tfds.features.Scalar(dtype=np.float32),
                        "depth_uncertainty": tfds.features.Scalar(dtype=np.float32),
                        "force_min": tfds.features.Scalar(dtype=np.float32),
                        "force_max": tfds.features.Scalar(dtype=np.float32),
                    }),
                    "episode_metadata": tfds.features.FeaturesDict({
                        "episode_id": tfds.features.Scalar(dtype=np.int64),
                        "source_file": tfds.features.Text(),
                        "annotation_key": tfds.features.Text(),
                        "data_source": tfds.features.Text(),
                        "task_id": tfds.features.Text(),
                        "split": tfds.features.Text(),
                        "slot_pair": tfds.features.Text(),
                        "success": tfds.features.Scalar(dtype=np.bool_),
                        "needs_review": tfds.features.Scalar(dtype=np.bool_),
                        "review_reasons": tfds.features.Text(),
                    }),
                }),
            )

        def _split_generators(self, dl_manager: Any) -> dict[str, Iterable[tuple[str, dict[str, Any]]]]:
            return {"train": self._generate_examples()}

        def _generate_examples(self) -> Iterable[tuple[str, dict[str, Any]]]:
            failures = 0
            for ordinal, episode in enumerate(self.episode_rows):
                result = process_episode(
                    episode,
                    np=np,
                    cv2=cv2,
                    image_size=image_size,
                    load_arrays=True,
                    mask_tactile_before_stage1=mask_tactile_before_stage1,
                    normalize_gripper=args.normalize_gripper_01,
                    absolute_gripper_action=args.absolute_gripper_action,
                    wrap_euler_action=args.wrap_euler_action,
                    raw_pressure_tactile_enabled=args.raw_pressure_tactile,
                    target_fps=args.target_fps,
                    depth_invalid_to_zero=args.depth_invalid_to_zero,
                )
                if result.steps is None:
                    failures += 1
                    print(f"[skip] {episode.rel_path}: {result.reason}")
                    continue
                key = make_episode_key(args.key_prefix, episode, ordinal)
                yield key, {
                    "steps": result.steps,
                    "episode_metadata": {
                        "episode_id": np.int64(ordinal),
                        "source_file": episode.rel_path,
                        "annotation_key": episode.annotation_key,
                        "data_source": episode.data_source,
                        "task_id": value_or(episode.row.get("task_id"), "unknown"),
                        "split": value_or(episode.row.get("split")),
                        "slot_pair": value_or(episode.row.get("slot_pair")),
                        "success": parse_bool(episode.row.get("success")),
                        "needs_review": episode.needs_review,
                        "review_reasons": value_or(episode.row.get("review_reasons")),
                    },
                }
            if failures:
                print(f"[build] skipped {failures} episodes")

    output_dir = repo_path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    builder = TransvtlaAnnotatedRlds(data_dir=output_dir, episode_rows=episodes)
    print(f"selected={len(episodes)} output_dir={output_dir}")
    builder.download_and_prepare()
    return 0


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Convert annotated TransVTLA sessions to RLDS/TFDS."
    )
    parser.add_argument("--manifest", required=True, help="annotation_manifest*.csv path")
    parser.add_argument("--output-dir", default="dataset/rlds_annotated", help="TFDS output directory")
    parser.add_argument("--data-source", choices=["all", "real", "sim"], default="all")
    parser.add_argument("--split", default="", help="Optional exact split filter")
    parser.add_argument("--max-episodes", type=int, default=None)
    parser.add_argument("--allow-review", action="store_true", help="Keep rows with needs_review=1")
    parser.add_argument("--include-unusable", action="store_true", help="Keep usable_for_aligned_training=0 rows")
    parser.add_argument("--image-size", type=int, default=224)
    parser.add_argument("--no-mask-tactile-before-stage1", action="store_true")
    parser.add_argument("--normalize-gripper-01", action="store_true", help="Clip state gripper to [0,1], dividing [0,1000] raw values by 1000.")
    parser.add_argument("--absolute-gripper-action", action="store_true", help="Write action[6] as next normalized gripper position instead of frame delta.")
    parser.add_argument("--wrap-euler-action", action="store_true", help="Wrap Euler action delta dimensions 3:6 into [-pi, pi].")
    parser.add_argument("--raw-pressure-tactile", action="store_true", help="Fallback to pressure/pressure.csv and build [16,20] normalized tactile windows when preprocessed NPZ is absent.")
    parser.add_argument("--target-fps", type=float, default=0.0, help="Optional visual timestep rate; 0 keeps source frames.")
    parser.add_argument("--depth-invalid-to-zero", action="store_true", help="Map uint16 depth 65535 invalid/far-clip pixels to 0 before resizing.")
    parser.add_argument("--dry-run", action="store_true", help="Validate selection and alignment only")
    parser.add_argument("--build", action="store_true", help="Write the TFDS/RLDS dataset")
    parser.add_argument("--version", default="3.0.0", help="TFDS builder version for --build")
    parser.add_argument("--key-prefix", default="transvtla")
    parser.add_argument("--show-failures", type=int, default=20)
    parser.add_argument("--fail-on-error", action="store_true", help="Make --dry-run nonzero if any episode fails")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    if args.dry_run == args.build:
        raise SystemExit("Specify exactly one of --dry-run or --build")
    if args.dry_run:
        return dry_run(args)
    return build(args)


if __name__ == "__main__":
    raise SystemExit(main())
